"""Bundle the existing page for HTML-only previews. No dependencies required."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
html = (ROOT / "index.html").read_text(encoding="utf-8")
css = (ROOT / "style.css").read_text(encoding="utf-8")
javascript = (ROOT / "script.js").read_text(encoding="utf-8")

stylesheet_tag = '<link rel="stylesheet" href="style.css">'
script_tag = '<script src="script.js" defer></script>'
if html.count(stylesheet_tag) != 1 or html.count(script_tag) != 1:
    raise SystemExit("index.html의 CSS/JavaScript 참조를 확인해 주세요.")
if "</style" in css.lower() or "</script" in javascript.lower():
    raise SystemExit("외부 파일에 HTML 종료 태그가 있어 안전하게 합칠 수 없습니다.")

html = html.replace(stylesheet_tag, "<style>\n" + css + "</style>")
html = html.replace(script_tag, "")
# Inline scripts do not honor defer: run only after the page elements exist.
html = html.replace("</body>", "<script>\n" + javascript + "</script>\n  </body>")
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by tools/build-preview.py. Edit index.html, style.css or script.js, then regenerate. -->", 1)
(ROOT / "preview.html").write_text(html, encoding="utf-8")
print("preview.html 생성 완료 — CSS와 JavaScript가 포함된 단일 HTML 파일입니다.")
